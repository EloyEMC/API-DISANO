def test_source_snapshot_keeps_count_and_batches_consistent_during_mutation(
    tmp_path: Path,
) -> None:
    database_path = tmp_path / "source.db"
    columns_sql = ", ".join(f'"{column}" TEXT' for column in PRODUCT_COLUMNS)
    values: list[object | None] = [None] * len(PRODUCT_COLUMNS)
    values[1] = "A-1"
    values[5] = "original"
    placeholders = ", ".join("?" for _ in PRODUCT_COLUMNS)
    with sqlite3.connect(database_path) as connection:
        connection.execute("PRAGMA journal_mode=WAL")
        connection.execute(f"CREATE TABLE productos ({columns_sql})")
        connection.execute(f"INSERT INTO productos VALUES ({placeholders})", values)
        connection.commit()

    with _open_source_snapshot(database_path) as (_, source_count, snapshot):
        assert source_count == 1
        with sqlite3.connect(database_path) as mutator:
            mutator.execute(
                'UPDATE productos SET "DESCRIPCION" = ? WHERE "CÓDIGO" = ?',
                ("mutated", "A-1"),
            )
            mutator.commit()

        rows = list(_read_batches(snapshot, 1))

    assert rows[0][0][5] == "original"
