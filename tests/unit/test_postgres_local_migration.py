class _ClosedAfterContextConnection:
    closed = False

    def __init__(self) -> None:
        self.rollback_calls = 0

    def __enter__(self) -> "_ClosedAfterContextConnection":
        return self

    def __exit__(self, *_: object) -> bool:
        self.closed = True
        return False

    def cursor(self) -> "_FailingCursor":
        return _FailingCursor()

    def rollback(self) -> None:
        self.rollback_calls += 1
        raise AssertionError("rollback must not run after the connection closes")

    def close(self) -> None:
        self.closed = True


class _FailingCursor:
    def __enter__(self) -> "_FailingCursor":
        return self

    def __exit__(self, *_: object) -> bool:
        return False

    def execute(self, *_: object) -> None:
        return None

    def executemany(self, *_: object) -> None:
        return None


@contextmanager
def _fake_source_snapshot(_: Path):
    yield PRODUCT_COLUMNS, 0, object()


def test_import_products_does_not_rollback_closed_connection(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    connection = _ClosedAfterContextConnection()
    monkeypatch.setattr(
        "migration.postgres_local_migrate.require_verified_postgres_backup",
        lambda *_: None,
    )
    monkeypatch.setattr(
        "migration.postgres_local_migrate._connect_postgres",
        lambda _: connection,
    )
    monkeypatch.setattr(
        "migration.postgres_local_migrate._open_source_snapshot",
        _fake_source_snapshot,
    )
    monkeypatch.setattr(
        "migration.postgres_local_migrate._read_batches",
        lambda *_: (_ for _ in ()).throw(RuntimeError("batch failed")),
    )

    with pytest.raises(RuntimeError, match="batch failed"):
        import_products(tmp_path / "source.db", "postgresql://localhost/db", 1)

    assert connection.rollback_calls == 0


